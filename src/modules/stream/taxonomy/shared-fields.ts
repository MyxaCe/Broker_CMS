import type { Field } from 'payload'

/**
 * Поля, общие для таксономий (ТЗ 1.1).
 *
 * Таксономии — первоклассные сущности, а не строки. Разница практическая:
 * переименование категории не требует правки каждой новости, а список
 * категорий нельзя засорить опечатками, потому что он выбирается, а не
 * вводится.
 */

/**
 * Тенант, которому принадлежит запись.
 *
 * Не обязательно сайт: категория может принадлежать бренду и использоваться
 * всеми его сайтами. Именно ради этого таксономия привязана к узлу дерева, а
 * не к листу — иначе одну и ту же «Аналитику» пришлось бы заводить двадцать
 * раз и следить, чтобы они не разошлись.
 */
export const ownerField: Field = {
  name: 'owner',
  type: 'relationship',
  relationTo: 'tenants',
  required: true,
  index: true,
  label: 'Владелец',
  admin: {
    description:
      'Бренд, регион или сайт. Запись доступна владельцу и всему его поддереву: категория бренда видна всем его сайтам.',
  },
}

/**
 * Машинное имя.
 *
 * Уникальность — на пару «владелец + slug», и она стоит в БД отдельной
 * миграцией: Payload не выражает составную уникальность в описании коллекции,
 * а проверка в приложении здесь бесполезна — между чтением и записью и
 * происходит гонка.
 */
export const slugField: Field = {
  name: 'slug',
  type: 'text',
  required: true,
  index: true,
  label: 'Машинное имя',
  validate: (value: unknown) => {
    if (typeof value !== 'string' || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(value)) {
      return 'Только строчные латинские буквы, цифры и дефис между ними.'
    }

    return true
  },
  admin: {
    description: 'Попадает в адреса. После публикации менять нельзя — ломаются ссылки.',
  },
}

export const titleField: Field = {
  name: 'title',
  type: 'text',
  required: true,
  label: 'Название',
}

export const descriptionField: Field = {
  name: 'description',
  type: 'textarea',
  label: 'Описание',
  admin: { description: 'Используется на странице раздела и в разметке для поисковых систем.' },
}

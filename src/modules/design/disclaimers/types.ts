/**
 * Дисклеймеры продукта (ТЗ 2.4, Р-028).
 *
 * Контракт разделён по двум осям, и это решение штаба, а не наша эстетика:
 *
 * - **ключи зависят от страницы**, потому что выводятся из состава её блоков;
 * - **тексты зависят от сайта и локали**, потому что это редакторский контент
 *   с переводом и юрисдикцией.
 *
 * Класть тексты в каждую страницу значило бы дублировать регуляторный текст
 * по всему манифесту — и получить двадцать его версий в момент правки.
 */

/**
 * Требуемые дисклеймеры одной страницы в одной локали.
 *
 * Ключи разложены **по источнику**, а не плоским списком (правка штаба к
 * Р-028). Плоский список на страницу теряет связь «этот дисклеймер про этот
 * калькулятор», а она может быть требованием регулятора, а не вкусом:
 * предупреждение о риске нередко обязано стоять рядом с тем, к чему
 * относится.
 *
 * Раскладку по-прежнему выбирает витрина. Данные лишь позволяют поставить
 * текст рядом с источником, а не только в подвал.
 */
export interface PageDisclaimers {
  readonly path: string
  readonly locale: string
  /**
   * Ключи, относящиеся к странице целиком.
   *
   * Сюда попадает то, что выведено из **глобальных областей** — шапки,
   * подвала, попапов. Тикер котировок в шапке требует дисклеймера о данных
   * на каждой странице, и привязать его к блоку страницы нельзя: такого
   * блока на странице нет.
   */
  readonly page: readonly string[]
  /** Ключи при блоке, из которого выведены. Путь — адрес блока в дереве. */
  readonly blocks: readonly {
    readonly path: string
    readonly type: string
    readonly keys: readonly string[]
  }[]
}

export interface DisclaimerFinding {
  readonly code: 'disclaimer-text-missing' | 'disclaimer-text-empty'
  readonly message: string
  readonly location: string
}

export interface DisclaimersSnapshot {
  /** Локаль → ключ → текст. Разрешено по цепочке тенанта на момент сборки. */
  readonly texts: Readonly<Record<string, Readonly<Record<string, string>>>>
  readonly pages: readonly PageDisclaimers[]
  readonly findings: readonly DisclaimerFinding[]
  /**
   * Сколько пар «страница × требуемый ключ» осмотрено.
   *
   * Не число страниц: страница без калькулятора и таблицы инструментов
   * дисклеймеров не требует, и считать её осмотренной значило бы объявить
   * охват там, где проверять было нечего (ADR-0029).
   */
  readonly examinedRequirements: number
}

export const EMPTY_DISCLAIMERS: DisclaimersSnapshot = {
  texts: {},
  pages: [],
  findings: [],
  examinedRequirements: 0,
}

/**
 * Срок годности списка разрешённых инструментов (Р-030, Р-042).
 *
 * Контракт `site-config.v1` отдаёт `settings.instrumentsExpiresAt` — момент,
 * после которого списку верить нельзя. Поле обязательное; у потребителя
 * отсутствие срока означает истёкший срок, то есть закрытую границу.
 *
 * ## Это не директива кеширования
 *
 * `Cache-Control` говорит о переиспользовании HTTP-ответа посредником, а срок
 * годности — о **действительности разрешений**. Команда `site-platform`
 * правильно отказалась читать `no-cache` как нулевой срок: такое прочтение
 * закрыло бы витрину навсегда. Величины разные, поэтому поле отдельное, а
 * заголовки выдачи остаются прежними (`private, no-cache` с `ETag`).
 *
 * ## От чего отсчитывается срок
 *
 * **От момента выдачи ответа, а не от `builtAt` релиза.** Разница
 * принципиальная, и выбор сделан осознанно.
 *
 * Срок годности здесь — это обещание источника: «если разрешения изменятся,
 * ты узнаешь вебхуком; но дольше этого окна списку не верь». Обещание
 * относится к моменту, когда мы ответили, а не к моменту, когда редактор
 * последний раз нажал «опубликовать». Срок от `builtAt` закрывал бы витрину
 * сайта, который просто давно не публиковался, — при полностью исправных
 * разрешениях. Гейт, который невозможно удовлетворить, отключают; мы это уже
 * проходили с гейтом комплаенса и с бюджетом бандла (Р-031).
 *
 * ## Почему значение именно такое
 *
 * Величина выведена, а не выбрана круглой.
 *
 * Нижняя граница задана потребителем: витрина переиспользует собранную
 * страницу **300 секунд** — `EDITORIAL_REUSE_WINDOW_SECONDS` в
 * `packages/tenant/src/expiry.ts`, и это же число стоит в
 * `apps/web/lib/tenant.ts` как `revalidate` (проверено по коду соседа, а не
 * по описанию в решении). Срок короче окна означал бы закрытую границу при
 * штатной работе — ровно та ошибка, от которой удержались, не прочитав
 * `no-cache` как нулевой срок.
 *
 * Срок, равный ровно одному окну, закрывал бы витрину от **одной** опоздавшей
 * перепроверки. Ложная тревога дороже, чем кажется: после двух-трёх таких
 * защиту отключают. Два пропуска подряд — это уже не задержка, а неработающий
 * канал обновления.
 *
 * Отсюда: **три окна потребителя, 900 секунд.** Два пропуска переживаются,
 * третий закрывает границу.
 *
 * Верхняя граница проверена отдельно: витрина — редакционный рубеж, а не
 * торговый (Р-030, п. 2), и лишние пятнадцать минут означают лишнюю страницу
 * в выдаче, а не разрешённую сделку. Торговый рубеж держит терминал, читая
 * конфигурацию живой. И главное: **сегодня верхней границы нет вовсе** — при
 * недошедшем вебхуке список живёт до следующей сборки. Поле не укорачивает
 * окно, оно делает его конечным.
 *
 * ## Почему значение не в окружении
 *
 * Это утверждение о том, как долго действительны разрешения, то есть свойство
 * источника, а не настройка развёртывания — та же логика, по которой порог
 * свежести котировок принадлежит MDS (Р-034). Переменная окружения добавила бы
 * контуру способ незаметно развести два стенда, а проверить её значение можно
 * было бы только чтением стенда.
 */

/**
 * Окно переиспользования страницы у витрины, в секундах.
 *
 * Копия чужой константы, и это осознанно: репозитории выкатываются порознь, и
 * импортировать её неоткуда. Значение сверено с кодом потребителя
 * (`packages/tenant/src/expiry.ts`), а тест ниже закрепляет **связь**: если
 * сосед изменит окно, срок придётся пересчитать, и об этом должно быть
 * известно до выкатки, а не после.
 */
export const CONSUMER_REUSE_WINDOW_SECONDS = 300

/**
 * Сколько окон потребителя переживает список.
 *
 * Два пропуска перепроверки — задержка, третий — неработающий канал.
 */
export const TOLERATED_REUSE_WINDOWS = 3

/** Срок годности списка, в секундах. 900 = 300 × 3. */
export const INSTRUMENTS_LIFETIME_SECONDS = CONSUMER_REUSE_WINDOW_SECONDS * TOLERATED_REUSE_WINDOWS

const LIFETIME_MS = INSTRUMENTS_LIFETIME_SECONDS * 1000

/**
 * Момент, после которого списку верить нельзя.
 *
 * Значение **квантуется** по сетке в одно время жизни. Причина не в экономии:
 * `ETag` выдачи — сильный валидатор, посчитанный по телу ответа, и ответ,
 * меняющийся на каждый запрос, превратил бы условный запрос в бесполезный, а
 * обещание «один и тот же кортеж измерений даёт байт-в-байт одинаковый ответ»
 * — в неправду. При квантовании свойство, которое действительно нужно,
 * сохраняется целиком: **одинаковый `ETag` означает одинаковое тело.**
 * Меняется более слабое — тело меняется раз в окно, и `ETag` вместе с ним,
 * честно.
 *
 * Отсюда и запас: срок всегда **строго больше** одного времени жизни и не
 * больше двух. Нижняя граница — то, что обещано потребителю; верхняя — цена
 * квантования.
 */
export function instrumentsExpiresAt(nowMs: number): string {
  if (!Number.isFinite(nowMs)) {
    /**
     * Негодные часы — это отказ, а не повод подставить правдоподобный момент.
     * Срок, посчитанный от `NaN`, дал бы `Invalid Date`, схема бы его не
     * пропустила, и наружу ушла бы `500` без объяснения. Разбор и приведение —
     * разные барьеры, и второй умеет портить то, что первый пропустил.
     */
    throw new RangeError('Срок годности списка нельзя посчитать: момент выдачи не число.')
  }

  const windowStart = Math.floor(nowMs / LIFETIME_MS) * LIFETIME_MS

  return new Date(windowStart + 2 * LIFETIME_MS).toISOString()
}

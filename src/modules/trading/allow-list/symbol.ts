/**
 * Канонический символ инструмента.
 *
 * Контракт платформы — **символы, а не числовые id** (Р-024). Числовая
 * нумерация живёт внутри терминала и наружу не выходит: перенумерация там
 * молча изменила бы, кому что разрешено торговать, а это регуляторная граница.
 */

/**
 * Что считается символом.
 *
 * Шаблон намеренно шире привычного `[A-Z]{6}`: во вселенной MDS сегодня есть
 * `1000SATSUSD`, `BROCCOLI714USD` и даже символы с иероглифами — это реальные
 * пары Binance, и запретить их значило бы запретить владельцу разрешить то,
 * что реально котируется.
 *
 * Запрещены ровно две вещи, и у каждой есть причина:
 *
 * - **пробельные символы** — символ попадает в сравнение по равенству у трёх
 *   потребителей, и `" BTCUSD"` там не совпадёт ни с чем, оставшись при этом
 *   видимым в списке как разрешённый;
 * - **запятая** — символы уезжают в `GET /v1/quotes?symbols=A,B,C`. Запятая
 *   внутри символа превращает одну запись списка в две, то есть разрешает то,
 *   чего в списке нет.
 */
export const SYMBOL_PATTERN = /^[^\s,]{1,32}$/u

/**
 * Приведение к каноническому виду.
 *
 * Выполняется **до** проверки и до сравнения с вселенной: иначе `btcusd`,
 * введённый руками, не нашёлся бы во вселенной и потребовал бы подтверждения
 * «такого символа в MDS нет» — отказ, у которого неверная причина, хуже
 * отсутствующего, потому что по нему пойдут чинить не то.
 */
export function normalizeSymbol(value: unknown): string {
  return typeof value === 'string' ? value.trim().toUpperCase() : ''
}

export function isValidSymbol(value: string): boolean {
  return SYMBOL_PATTERN.test(value)
}

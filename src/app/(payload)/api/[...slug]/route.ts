import config from '@payload-config'
import { REST_DELETE, REST_GET, REST_OPTIONS, REST_PATCH, REST_POST } from '@payloadcms/next/routes'

/**
 * Служебный HTTP-слой админки.
 *
 * > [!] Это НЕ публичная дверь к данным.
 *
 * Он смонтирован потому, что интерфейс редактора без него неработоспособен:
 * загрузка файлов, обновление сессии и часть операций идут через него.
 * Полностью отключить REST — значит остаться без админки.
 *
 * Что делает его не второй дверью (ADR-0009):
 *
 *  1. К нему применяются те же правила доступа, что и везде: анонимный запрос
 *     отклоняется, а аутентифицированный ограничен привязкой к тенантам
 *     (ADR-0012). Здесь нет отдельной модели прав.
 *  2. Он не является контрактом для потребителей: сайт, кабинет и терминал
 *     ходят исключительно в `/v1`, где каждый ответ валидируется схемой.
 *  3. Он объявлен в инвентаризации маршрутов — появление новой поверхности
 *     рядом с ним уронит CI.
 *  4. На проде его доступность дополнительно ограничивается периметром
 *     (обратный прокси) — остаток TASK-006, зависит от Q-005.
 *
 * GraphQL не монтируется вовсе: `graphQL.disable` в конфигурации, и файлов
 * маршрутов для него здесь нет.
 */
export const GET = REST_GET(config)
export const POST = REST_POST(config)
export const DELETE = REST_DELETE(config)
export const PATCH = REST_PATCH(config)
export const OPTIONS = REST_OPTIONS(config)

/**
 * Профиль юрисдикции — место, где живут регуляторные числа (CMS-24, Р-237).
 *
 * До сих пор регуляторные величины были разбросаны: порог закрытия по марже —
 * в настройках площадки, плечо — в коде, защита от отрицательного баланса — в
 * поведении, категория клиента — нигде (Р-237). Профиль собирает их в одну
 * **именованную сущность**, и «переключаемая архитектура» перестаёт быть
 * намерением: добавить вторую страну — значит завести вторую запись, а не
 * искать по всему коду, что именно поменять, в области, где ошибка стоит
 * лицензии.
 *
 * Профиль по умолчанию — **Сейшелы** (Р-236, Р-237). Это не «выбрали страну», а
 * «выбрали первый профиль»: пороги, деление клиентов и ограничения плеча стали
 * настройкой профиля, а не константами.
 *
 * Конкретные регуляторные числа других юрисдикций здесь НЕ выдуманы: границы,
 * которые задаёт владелец/deploy (`marginCloseOutPercent`, `maxLeverage`,
 * `dataResidency`), оставлены точками расширения со значением `null` — «не
 * задано», отличимым от нуля. Нуль у порога — законное значение, и путать его с
 * «ещё не решили» нельзя по тому же уроку, что `null` против нуля у денежной
 * суммы.
 */

/**
 * Деление клиентов на категории (Р-236).
 *
 * `client_category` — атрибут счёта: розничный или профессиональный. Профиль
 * юрисдикции задаёт, какие категории вообще существуют на площадке; какая из
 * них у конкретного счёта — его собственное поле, и живёт оно в торговой части,
 * а не здесь.
 */
export const CLIENT_CATEGORIES = ['retail', 'professional'] as const

export type ClientCategory = (typeof CLIENT_CATEGORIES)[number]

export const CLIENT_CATEGORY_LABELS: Readonly<Record<ClientCategory, string>> = {
  retail: 'Розничный',
  professional: 'Профессиональный',
}

export function isClientCategory(value: unknown): value is ClientCategory {
  return typeof value === 'string' && (CLIENT_CATEGORIES as readonly string[]).includes(value)
}

/**
 * Код профиля по умолчанию.
 *
 * Профиль связан с тенантом по коду юрисдикции (`settings.jurisdiction`), а не
 * ссылкой: код юрисдикции уже ездит через весь контракт выдачи и правила
 * видимости (Р-045, Р-061) строкой. Профиль подбирается к этой строке, и
 * «переключить юрисдикцию» означает поменять код у тенанта — механизм, который
 * уже есть, а не второй, заведённый ради профиля.
 */
export const DEFAULT_JURISDICTION_CODE = 'SC'

/**
 * Профиль юрисдикции.
 *
 * `null` у числовой границы означает «не задано ни в этом профиле» — это точка
 * расширения, которую заполняет владелец/deploy, а не наш нуль. Отличать их
 * обязательно: подставленное правдоподобное число на месте «ещё не решили» —
 * это регуляторная граница, которую никто не назначал.
 */
export interface JurisdictionProfile {
  /** Код юрисдикции, которым профиль связан с тенантом. Совпадает с `settings.jurisdiction`. */
  readonly code: string
  /** Человекочитаемое название. */
  readonly name: string
  /** Профиль по умолчанию. Ровно один на площадку — сегодня Сейшелы. */
  readonly isDefault: boolean
  /** Какие категории клиентов существуют в этой юрисдикции (Р-236). */
  readonly clientCategories: readonly ClientCategory[]
  /**
   * Защита от отрицательного баланса как **видимый включённый флаг**, а не
   * вшитое поведение (Р-226, Р-236, Р-281).
   *
   * На Сейшелах она не обязательна — мы даём её по своему выбору. Флаг обязан
   * быть виден включённым, а не намертво зашит: иначе при добавлении второй
   * юрисдикции нечем ответить, почему он там такой же.
   */
  readonly negativeBalanceProtection: boolean
  /**
   * Порог закрытия по марже, процентами (Р-226). Точка расширения: конкретное
   * число — решение владельца/площадки. `null` — «не задано в профиле».
   */
  readonly marginCloseOutPercent: number | null
  /**
   * Потолок плеча (Р-237, TRM-53). Точка расширения: конкретное число —
   * решение владельца. Портфельное плечо (Standard/Pro/ENC Prime) живёт в
   * site-platform (WEB-44) и профилем не отменяется — профиль задаёт верхнюю
   * границу юрисдикции, а не стартовые значения портфелей. `null` — «не задан».
   */
  readonly maxLeverage: number | null
  /**
   * Что где можно хранить — регуляторные ограничения на размещение данных.
   * Заглушка-точка расширения: конкретика — решение владельца. `null` — «не
   * задано».
   */
  readonly dataResidency: string | null
  /** Регулятор, чьё требование исполняет профиль. Справочно; `null` — не указан. */
  readonly regulator: string | null
}

/**
 * Профиль по умолчанию — Сейшелы (Р-236, Р-237).
 *
 * Заполнены только те значения, которые являются НАШИМ решением и не требуют
 * владельца: деление на розничных и профессиональных (Р-236) и защита от
 * отрицательного баланса, включённая по нашему выбору (Р-281). Регуляторные
 * числа, которые задаёт владелец/deploy, оставлены `null` — точками расширения,
 * а не выдуманными величинами.
 */
export const SEYCHELLES_DEFAULT_PROFILE: JurisdictionProfile = {
  code: DEFAULT_JURISDICTION_CODE,
  name: 'Сейшелы',
  isDefault: true,
  clientCategories: ['retail', 'professional'],
  negativeBalanceProtection: true,
  marginCloseOutPercent: null,
  maxLeverage: null,
  dataResidency: null,
  regulator: null,
}

/**
 * Выбирает действующий профиль по умолчанию из набора.
 *
 * Механизм «по умолчанию — Сейшелы» названный и проверяемый: берётся запись с
 * флагом `isDefault`; если её нет — запись с кодом Сейшел; если нет и её —
 * встроенный `SEYCHELLES_DEFAULT_PROFILE`. Последняя ступень гарантирует, что
 * площадка без заведённых профилей всё равно имеет дефолт, а не пустоту на
 * месте регуляторного набора.
 *
 * При нескольких записях с флагом побеждает первая по коду: порядок не должен
 * зависеть от того, как строки пришли из базы.
 */
export function resolveDefaultProfile(
  profiles: readonly JurisdictionProfile[],
): JurisdictionProfile {
  const [firstFlagged] = profiles
    .filter((profile) => profile.isDefault)
    .sort((a, b) => a.code.localeCompare(b.code))

  if (firstFlagged) {
    return firstFlagged
  }

  const byCode = profiles.find((profile) => profile.code === DEFAULT_JURISDICTION_CODE)

  return byCode ?? SEYCHELLES_DEFAULT_PROFILE
}

/**
 * Подбирает профиль к коду юрисдикции тенанта.
 *
 * `null`, когда профиля с таким кодом нет: это отличимо от профиля по
 * умолчанию. Молча подставить дефолт значило бы применить сейшельские пороги к
 * стране, у которой их никто не сверял, — та же ошибка, что число без валюты
 * (Р-293), только в регуляторике. Выбор «брать дефолт или отказать» —
 * потребителя (TRM-45), и он должен видеть, что профиля не нашлось.
 */
export function profileForCode(
  profiles: readonly JurisdictionProfile[],
  code: string | null | undefined,
): JurisdictionProfile | null {
  if (typeof code !== 'string' || code.trim() === '') {
    return null
  }

  return profiles.find((profile) => profile.code === code.trim()) ?? null
}

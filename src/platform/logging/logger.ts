import pino from 'pino'

import { ensureEnv } from '../config/env'

import type { Logger } from 'pino'

/**
 * Журнал приложения (ТЗ разд. 7).
 *
 * Структурный, а не текстовый: записи читает не только человек, но и система
 * сбора. Текстовая строка вида «не удалось опубликовать событие 42» не
 * фильтруется по сайту и не агрегируется по причине.
 *
 * Уровень берётся из окружения. Это единственное поле конфигурации с
 * умолчанием — оно не гейтит ни доступ, ни целостность данных.
 */

/**
 * Поля, которые никогда не попадают в журнал.
 *
 * Список именно запретительный, а не разрешительный: разрешительный требует
 * помнить о нём при каждом новом поле, а забытое поле утекает молча. Пути
 * покрывают и вложенные объекты — секрет чаще приходит внутри «контекста»,
 * чем отдельным аргументом.
 */
const REDACTED_PATHS = [
  'password',
  '*.password',
  'secret',
  '*.secret',
  'secretHash',
  '*.secretHash',
  'authorization',
  '*.authorization',
  'headers.authorization',
  'token',
  '*.token',
  'plaintext',
  '*.plaintext',
]

let root: Logger | null = null

/**
 * Журнал не должен требовать полного окружения, чтобы записать «окружение
 * неверно»: иначе первое же сообщение, ради которого он нужен, невозможно
 * записать. Конфигурацию гейтит `ensureEnv` там, где это действительно важно —
 * при старте приложения; здесь её отсутствие означает лишь уровень по умолчанию.
 */
function configuredLevel(): string {
  try {
    return ensureEnv().LOG_LEVEL
  } catch {
    return 'info'
  }
}

/**
 * Настройки журнала отдельной функцией: тест собирает логгер с ровно теми же
 * настройками, но пишущий в память. Иначе проверялась бы копия настроек, а не
 * они сами — и расхождение между проверенным и работающим осталось бы незаметным.
 */
export function loggerOptions() {
  return {
    level: configuredLevel(),
    redact: { paths: REDACTED_PATHS, censor: '[скрыто]' },
    /**
     * Время в ISO, а не в миллисекундах эпохи: журнал читают люди в момент
     * разбирательства, и перевод отметки времени в голове — лишний шаг там,
     * где и без того тяжело.
     */
    timestamp: pino.stdTimeFunctions.isoTime,
  }
}

function rootLogger(): Logger {
  root ??= pino(loggerOptions())

  return root
}

/**
 * Журнал с постоянными полями.
 *
 * `component` обязателен: запись без указания источника невозможно ни
 * отфильтровать, ни отнести к чему-либо при разборе инцидента.
 */
export function createLogger(bindings: { component: string } & Record<string, unknown>): Logger {
  return rootLogger().child(bindings)
}
